#!/usr/bin/env node
// tools/write-manifest.mjs — rewrite data/art-manifest.js and data/audio-manifest.js from what is
// actually on disk. Never invents an entry; zero-length files are skipped.
import { readdir, writeFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT } from './load.mjs';

async function scan(dir, exts) {
  let names = [];
  try { names = (await readdir(join(ROOT, dir))).sort(); } catch {}
  const out = {};
  for (const f of names) {
    const dot = f.lastIndexOf('.');
    const ext = f.slice(dot).toLowerCase();
    if (dot < 0 || !exts.includes(ext)) continue;
    if ((await stat(join(ROOT, dir, f))).size < 1) { console.error('SKIP zero-length ' + dir + '/' + f); continue; }
    const key = f.slice(0, dot);
    // when a key has several formats, prefer the earliest in `exts` (.webp, then .png, then .jpg)
    if (out[key] && exts.indexOf(out[key].slice(out[key].lastIndexOf('.')).toLowerCase()) <= exts.indexOf(ext)) continue;
    out[key] = f;
  }
  return Object.fromEntries(Object.entries(out).map(([k, f]) => [k, `${dir}/${f}`]));
}
const body = (obj) => '{' + Object.entries(obj).map(([k, v]) => `\n ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',') + (Object.keys(obj).length ? '\n' : '') + '}';

const art = await scan('art/cards', ['.webp', '.png', '.jpg']);
const sfx = {};   // audio arrives with the sound stage (TODO.md)

await writeFile(join(ROOT, 'data', 'art-manifest.js'),
`// GENERATED by tools/write-manifest.mjs from the files in art/cards/. Do not edit by hand.
window.MF.artManifest = ${body(art)};
`);
await writeFile(join(ROOT, 'data', 'audio-manifest.js'),
`// GENERATED by tools/write-manifest.mjs from the files in audio/sfx/. Do not edit by hand.
// A voice named here plays its recorded sample instead of the synthesised one in js/audio.js.
window.MF.audioManifest = ${body(sfx)};
`);
console.log(`${Object.keys(art).length} art entries, ${Object.keys(sfx).length} audio entries written`);
